/// Spacing scale used across the app.
abstract final class AppSpacing {
  /// 2 logical pixels.
  static const xxs = 2.0;

  /// 4 logical pixels.
  static const xs = 4.0;

  /// 8 logical pixels.
  static const sm = 8.0;

  /// 12 logical pixels.
  static const smMd = 12.0;

  /// 16 logical pixels.
  static const md = 16.0;

  /// 20 logical pixels. Default horizontal padding of screens.
  static const lg = 20.0;

  /// 24 logical pixels.
  static const lgXl = 24.0;

  /// 32 logical pixels.
  static const xl = 32.0;

  /// 40 logical pixels.
  static const xxl = 40.0;

  /// 48 logical pixels.
  static const xxxl = 48.0;

  /// 64 logical pixels.
  static const huge = 64.0;
}
