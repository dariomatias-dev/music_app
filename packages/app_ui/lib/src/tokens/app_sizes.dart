/// Icon size scale used across the app.
abstract final class AppSizes {
  /// 14 logical pixels.
  static const iconExtraSmall = 14.0;

  /// 18 logical pixels.
  static const iconSmall = 18.0;

  /// 22 logical pixels.
  static const iconMedium = 22.0;

  /// 28 logical pixels.
  static const iconLarge = 28.0;

  /// 32 logical pixels.
  static const iconExtraLarge = 32.0;

  /// Smallest side length any tappable element should occupy (matches
  /// iOS's 44pt Human Interface Guidelines minimum, which also satisfies
  /// Android's 48dp guideline once combined with typical device density).
  static const minTouchTarget = 44.0;
}
